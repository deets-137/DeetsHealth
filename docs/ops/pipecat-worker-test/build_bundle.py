"""Put the committed agent, its data files and the ehr tape into the test Worker's src/.

Usage: python build_bundle.py <copy of HEAD> <tape.json> <worker src>
"""

import json
import shutil
import sys
from pathlib import Path

head, tape_path, src = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
tape = json.loads(tape_path.read_text(encoding="utf-8"))

dest = src / "deets_agent"
if dest.exists():
    shutil.rmtree(dest)
shutil.copytree(head / "agent" / "deets_agent", dest, ignore=shutil.ignore_patterns("__pycache__"))

# Data files, by their path under the repo root. A Python Worker bundles code, so these ride in
# a module and are written to the Worker's in-memory file system at start.
files: dict[str, str] = {}
for p in sorted((head / "agent" / "prompts").glob("*.md")):
    files[f"agent/prompts/{p.name}"] = p.read_text(encoding="utf-8")
files["ehr/fixtures/hospital.json"] = (head / "ehr" / "fixtures" / "hospital.json").read_text(encoding="utf-8")
for key in tape["keys"]:
    p = head / "agent" / "tests" / "replays" / f"{key}.json"
    files[f"agent/tests/replays/{key}.json"] = p.read_text(encoding="utf-8")

(src / "bundle_data.py").write_text(
    '"""Generated by build_bundle.py: the agent\'s data files and one kept script\'s ehr tape."""\n\n'
    f"FILES = {files!r}\n\n"
    f"TAPE = {tape!r}\n",
    encoding="utf-8",
)
size = sum(len(v) for v in files.values())
print(f"files {len(files)} ({size // 1024} KiB), replay files {len(tape['keys'])}, ehr answers {len(tape['tape'])}")
